def inputs(suite):
    paths=set()
    if suite=='frontend':
        paths.update(p for p in (ROOT/'src').rglob('*') if p.is_file())
        paths.update(ROOT.glob('tsconfig*.json'))
        paths.update(ROOT/p for p in ['package.json','package-lock.json','vite.config.ts','index.html'])
    elif suite=='rust':
        for directory in ['crates/reservoir-core','src-tauri/src','src-tauri/capabilities','src-tauri/permissions','scripts']:
            paths.update(p for p in (ROOT/directory).rglob('*') if p.is_file() and p.suffix in {'.rs','.toml','.json','.txt','.bin','.py','.mjs'} and 'autogenerated' not in p.parts and '__pycache__' not in p.parts)
        paths.update(ROOT/p for p in ['Cargo.toml','Cargo.lock','rust-toolchain.toml','src-tauri/build.rs','src-tauri/Cargo.toml','src-tauri/tauri.conf.json','package.json','package-lock.json'])
    else:raise ValueError('Unknown suite')
    return {str(p.relative_to(ROOT)):sha(p) for p in sorted(paths)}

def attempt(value):
    if not re.fullmatch(r'[0-9]{2}',value):raise ValueError('Use a two-digit attempt ID')
    return value

def commands(suite):
    if suite=='frontend':
        return [('frontend-tests',[str(NODE/'npm'),'test']),('frontend-build',[str(NODE/'npm'),'run','build']),('frontend-reference',['python3','scripts/check_reference.py'])]
    raise ValueError('This wording tranche does not repeat Rust checks')


def execute(name,command,number,env):
    log=OUT/f'{name}-{number}.log';start=time.monotonic()
    row={'name':name,'command':command,'startedAtUtc':utc(),'log':log.name}
    with log.open('x') as f:result=subprocess.run(command,cwd=ROOT,env=env,stdout=f,stderr=subprocess.STDOUT)
    row.update(endedAtUtc=utc(),elapsedSeconds=time.monotonic()-start,exitCode=result.returncode,sha256=sha(log))
    text=log.read_text(errors='replace')
    if name=='frontend-tests':
        match=re.search(r'Test Files\s+(\d+) passed.*?Tests\s+(\d+) passed',text,re.S)
        row['counts']={'testFiles':int(match[1]),'tests':int(match[2])} if match else None
    if name.endswith('-tests') and name!='frontend-tests':
        found=re.findall(r'test result: ok\. (\d+) passed; (\d+) failed; (\d+) ignored;',text)
        row['passedTests']=sum(int(x[0]) for x in found);row['ignoredTests']=sum(int(x[2]) for x in found)
    return row


PRIOR_RUST = OUT.parent / '2026-10-15-observatory-fields-0.22.0/rust-checks-01.json'
PRIOR_RUST_SHA = '4b531d15dcabcf4097225e809019d54f6405d66ba6e091103f68baddb481a039'
OLD_VERSION, VERSION = '0.22.0', '0.22.1'
METADATA = ('package.json', 'package-lock.json', 'Cargo.lock', 'src-tauri/Cargo.toml', 'src-tauri/tauri.conf.json')

def normalized_metadata(path, data):
    text = data.decode('utf-8')
    if path in ('package.json', 'src-tauri/tauri.conf.json'):
        assert json.loads(text)['version'] == VERSION, path
        text, count = re.subn(r'("version"\s*:\s*")0\.22\.1(")', rf'\g<1>{OLD_VERSION}\2', text)
        assert count == 1, path
    elif path == 'package-lock.json':
        value=json.loads(text)
        assert value['version'] == VERSION and value['packages']['']['version'] == VERSION, path
        # The first two version occurrences are the document and root package.
        # Dependency records must remain byte-exact to the old qualified lock.
        text, count = re.subn(r'("version"\s*:\s*")0\.22\.1(")', rf'\g<1>{OLD_VERSION}\2', text, count=2)
        assert count == 2, path
    elif path == 'src-tauri/Cargo.toml':
        text,count=re.subn(r'(?m)^(version = ")0\.22\.1(")$',rf'\g<1>{OLD_VERSION}\2',text)
        assert count == 1, path
    elif path == 'Cargo.lock':
        text,count=re.subn(r'(\[\[package\]\]\nname = "reservoir-scope-desktop"\nversion = ")0\.22\.1(")',rf'\g<1>{OLD_VERSION}\2',text)
        assert count == 1, path
    else:raise ValueError('Unexpected version-metadata path')
    return text.encode('utf-8')

def qualified_basis(path=PRIOR_RUST):
    assert path.resolve() == PRIOR_RUST.resolve(), 'Use the exact qualified 0.22 Rust receipt'
    assert sha(path) == PRIOR_RUST_SHA, 'Qualified 0.22 Rust receipt changed'
    value=json.loads(path.read_bytes())
    assert value['passed'] and value['sourceUnchanged']
    return value, {r['path']:r['sha256'] for r in value['sourceAfter']}

def validate_metadata():
    _, basis=qualified_basis()
    values=[]
    for name in METADATA:
        data=(ROOT/name).read_bytes()
        normalized=hashlib.sha256(normalized_metadata(name,data)).hexdigest()
        assert normalized == basis[name], 'Unexpected non-version metadata change: '+name
        values.append({'path':name,'sha256':hashlib.sha256(data).hexdigest(),'normalizedTo022Sha256':normalized,'qualified022Sha256':basis[name]})
    return values

def validate_rust_reuse(path=PRIOR_RUST):
    prior,basis=qualified_basis(path)
    current=inputs('rust')
    assert current.keys()==basis.keys(), 'Qualified Rust/input file membership changed'
    for name,digest in current.items():
        actual=hashlib.sha256(normalized_metadata(name,(ROOT/name).read_bytes())).hexdigest() if name in METADATA else digest
        assert actual == basis[name], 'Rust qualification cannot be carried forward: '+name
    return {'schema':'reservoir-rust-qualification-reuse-v1','checkedAtUtc':utc(),'passed':True,
            'priorReceipt':{'path':str(path.resolve()),'sha256':sha(path)},
            'scope':'0.22 Rust tests and strict Clippy carried forward by exact input equality, allowing only the app version bump in five metadata files. No Rust test or Clippy rerun.',
            'metadata':validate_metadata(),'sourceBefore':current,
            'priorChecks':[{'name':x['name'],'exitCode':x['exitCode'],'passedTests':x.get('passedTests'),'ignoredTests':x.get('ignoredTests')} for x in prior['checks']]}
