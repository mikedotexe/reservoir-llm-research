"""Receipt helpers for explicitly invoked 0.22 checks. Import has no runtime action."""
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import os
import re
import subprocess
import time

ROOT=Path(__file__).resolve().parents[2]
OUT=Path(__file__).resolve().parent
NODE=Path('/Users/v/.nvm/versions/node/v20.20.1/bin')

def utc():return datetime.now(timezone.utc).isoformat()
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def environment():
    env=os.environ.copy()
    env.update(DEVELOPER_DIR='/Applications/Xcode.app/Contents/Developer',SDKROOT='/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX26.2.sdk',CARGO_INCREMENTAL='0',CARGO_BUILD_JOBS='2',PATH='/Users/v/.cargo/bin:'+str(NODE)+':'+os.environ['PATH'])
    return env

def inputs(suite):
    paths=set()
    if suite=='frontend':
        paths.update(p for p in (ROOT/'src').rglob('*') if p.is_file())
        paths.update(ROOT.glob('tsconfig*.json'))
        paths.update(ROOT/p for p in ['package.json','package-lock.json','vite.config.ts'])
    elif suite=='rust':
        for directory in ['crates/reservoir-core','src-tauri/src','src-tauri/capabilities','src-tauri/permissions','scripts']:
            paths.update(p for p in (ROOT/directory).rglob('*') if p.is_file() and p.suffix in {'.rs','.toml','.json','.txt','.bin','.py','.mjs'} and 'autogenerated' not in p.parts and '__pycache__' not in p.parts)
        paths.update(ROOT/p for p in ['Cargo.toml','Cargo.lock','rust-toolchain.toml','src-tauri/build.rs','src-tauri/Cargo.toml','src-tauri/tauri.conf.json','package.json','package-lock.json'])
    else:raise ValueError('Unknown suite')
    return {str(p.relative_to(ROOT)):sha(p) for p in sorted(paths)}

def attempt(value):
    if not re.fullmatch(r'[0-9]{2}',value):raise ValueError('Use a two-digit attempt ID')
    return value

def commands(suite):
    if suite=='frontend':
        return [('frontend-tests',[str(NODE/'npm'),'test']),('frontend-typescript',[str(NODE/'node'),'node_modules/typescript/bin/tsc','--noEmit'])]
    return [('reference',['python3','scripts/check_reference.py']),('resource-staging',[str(NODE/'npm'),'run','prepare:resources']),('rust-format',['cargo','fmt','--all','--','--check']),('core-tests',['cargo','test','--locked','-p','reservoir-core','--all-targets']),('desktop-tests',['cargo','test','--locked','-p','reservoir-scope-desktop']),('core-clippy',['cargo','clippy','--locked','-p','reservoir-core','--all-targets','--','-D','warnings']),('desktop-clippy',['cargo','clippy','--locked','-p','reservoir-scope-desktop','--all-targets','--','-D','warnings'])]

def execute(name,command,number,env):
    log=OUT/f'{name}-{number}.log';start=time.monotonic()
    row={'name':name,'command':command,'startedAtUtc':utc(),'log':log.name}
    with log.open('x') as f:result=subprocess.run(command,cwd=ROOT,env=env,stdout=f,stderr=subprocess.STDOUT)
    row.update(endedAtUtc=utc(),elapsedSeconds=time.monotonic()-start,exitCode=result.returncode,sha256=sha(log))
    text=log.read_text(errors='replace')
    if name=='frontend-tests':
        match=re.search(r'Test Files\s+(\d+) passed.*?Tests\s+(\d+) passed',text,re.S)
        row['counts']={'testFiles':int(match[1]),'tests':int(match[2])} if match else None
    if name.endswith('-tests') and name!='frontend-tests':
        found=re.findall(r'test result: ok\. (\d+) passed; (\d+) failed; (\d+) ignored;',text)
        row['passedTests']=sum(int(x[0]) for x in found);row['ignoredTests']=sum(int(x[2]) for x in found)
    return row
