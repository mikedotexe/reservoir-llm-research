#!/usr/bin/env python3
"""Capture source/package identity and observed signing status; never build or launch.

Optional check results are caller-supplied evidence, explicitly distinguished from
commands executed by this tool. Missing checks and human gates remain unexecuted.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import plistlib
import stat
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
DESKTOP = ROOT / "desktop/ReservoirScope"
EXCLUDED_PARTS = {"node_modules", "target", "dist", "__pycache__", ".pytest_cache", "validation"}
EXCLUDED_PREFIXES = (
    "desktop/ReservoirScope/src-tauri/gen/",
    "desktop/ReservoirScope/src-tauri/resources/",
    "desktop/ReservoirScope/src-tauri/permissions/autogenerated/",
)
CHECKS = {
    "reference-integrity": "Frozen native source/resource identity check",
    "resource-staging-tests": "Resource staging and mutation tests",
    "frontend-tests": "Frontend unit tests",
    "frontend-build": "TypeScript and frontend production build",
    "desktop-boundary-tests": "Rust desktop file/resource boundary tests",
    "core-conformance-tests": "Rust core conformance tests",
    "core-clippy": "Rust core strict Clippy check",
    "swift-export-verification": "Independent native Swift verification of Rust exports",
    "macos-package-build": "Tauri macOS package build",
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_entry(path: Path, relative: str, *, include_mode: bool = False) -> dict:
    metadata = path.lstat()
    if stat.S_ISLNK(metadata.st_mode):
        return {"path": relative, "kind": "symlink", "target": os.readlink(path)}
    if not stat.S_ISREG(metadata.st_mode):
        raise ValueError(f"Unexpected non-regular input: {path}")
    with path.open("rb") as source:
        before = os.fstat(source.fileno())
        digest = hashlib.sha256()
        size = 0
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
            size += len(chunk)
        after = os.fstat(source.fileno())
    identity = lambda value: (value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns)
    if identity(before) != identity(after) or before.st_size != size or identity(metadata) != identity(before):
        raise ValueError(f"Input changed while hashing: {path}")
    result = {"path": relative, "kind": "file", "bytes": size, "sha256": digest.hexdigest()}
    if include_mode:
        result["mode"] = oct(stat.S_IMODE(metadata.st_mode))
    return result


def inventory_digest(entries: list[dict]) -> str:
    return sha256(json.dumps(entries, sort_keys=True, separators=(",", ":")).encode())


def source_inventory(root: Path = ROOT) -> list[dict]:
    result = []
    for source_root in (root / "desktop/ReservoirScope", root / "shared/reservoir-scope"):
        for parent, directories, filenames in os.walk(source_root, followlinks=False):
            parent_path = Path(parent)
            directories[:] = sorted(d for d in directories if d not in EXCLUDED_PARTS
                                    and not any(((parent_path / d).relative_to(root).as_posix() + "/").startswith(p) for p in EXCLUDED_PREFIXES))
            # Symlink directories must be represented without following external data.
            for directory in directories[:]:
                path = parent_path / directory
                if path.is_symlink():
                    result.append(file_entry(path, path.relative_to(root).as_posix()))
                    directories.remove(directory)
            for filename in sorted(filenames):
                path = parent_path / filename
                relative = path.relative_to(root).as_posix()
                if path.suffix in {".pyc", ".pyo"} or filename == ".DS_Store":
                    continue
                result.append(file_entry(path, relative))
    workflow = root / ".github/workflows/tauri.yml"
    if workflow.is_file():
        result.append(file_entry(workflow, workflow.relative_to(root).as_posix()))
    return sorted(result, key=lambda item: item["path"])


def observe(command: list[str], cwd: Path = DESKTOP) -> dict:
    try:
        result = subprocess.run(command, cwd=cwd, capture_output=True, text=True, timeout=30)
        return {"command": command, "exitCode": result.returncode,
                "stdout": result.stdout.strip()[:16_384], "stderr": result.stderr.strip()[:16_384]}
    except (OSError, subprocess.TimeoutExpired) as error:
        return {"command": command, "exitCode": None, "error": str(error)}


def package_inventory(app: Path) -> dict:
    if app.suffix != ".app" or not app.is_dir() or app.is_symlink():
        raise ValueError("--app must select an existing local .app directory")
    info_path = app / "Contents/Info.plist"
    info = plistlib.loads(info_path.read_bytes())
    executable = info.get("CFBundleExecutable")
    if not isinstance(executable, str) or not executable or Path(executable).name != executable or "/" in executable or "\\" in executable:
        raise ValueError("App has no safe CFBundleExecutable filename")
    entries = []
    for parent, directories, filenames in os.walk(app, followlinks=False):
        directories.sort()
        for name in directories[:]:
            path = Path(parent) / name
            if path.is_symlink():
                entries.append(file_entry(path, path.relative_to(app).as_posix(), include_mode=True))
                directories.remove(name)
        for name in sorted(filenames):
            path = Path(parent) / name
            entries.append(file_entry(path, path.relative_to(app).as_posix(), include_mode=True))
    entries.sort(key=lambda item: item["path"])
    executable_path = f"Contents/MacOS/{executable}"
    binary = next((entry for entry in entries if entry["path"] == executable_path and entry["kind"] == "file"), None)
    if binary is None:
        raise ValueError("App executable is missing or is not a regular file")
    return {"name": app.name, "bundleIdentifier": info.get("CFBundleIdentifier"),
            "version": info.get("CFBundleShortVersionString"), "build": info.get("CFBundleVersion"),
            "binary": binary, "inventorySha256": inventory_digest(entries), "files": entries}


def reported_checks(path: Path | None) -> tuple[list[dict], dict | None]:
    checks = {key: {"id": key, "description": description, "status": "unexecuted",
                    "evidenceOrigin": "No execution result supplied"} for key, description in CHECKS.items()}
    source = None
    if path is not None:
        data = path.read_bytes()
        if len(data) > 65_536:
            raise ValueError("Check evidence exceeds 64 KiB")
        supplied = json.loads(data)
        if not isinstance(supplied, list):
            raise ValueError("--checks-file must contain a JSON array")
        seen = set()
        for item in supplied:
            if not isinstance(item, dict) or item.get("id") not in checks or item["id"] in seen:
                raise ValueError("Unknown or duplicated check id")
            if item.get("status") not in {"passed", "failed", "incomplete", "blocked", "unexecuted"}:
                raise ValueError("Unsupported check status")
            if item["status"] != "unexecuted" and (not item.get("command") or not item.get("evidence")):
                raise ValueError("Executed check claims require command and evidence")
            seen.add(item["id"])
            checks[item["id"]].update(item)
            checks[item["id"]]["evidenceOrigin"] = "Caller-supplied observation; not executed by receipt capture"
        source = {"name": path.name, "sha256": sha256(data), "bytes": len(data)}
    return list(checks.values()), source


def capture(app: Path, checks_file: Path | None, notes: list[str], archive: Path | None = None) -> dict:
    source_before = source_inventory()
    package_before = package_inventory(app)
    archive_before = file_entry(archive, archive.name) if archive is not None else None
    if archive_before is not None and archive_before["kind"] != "file":
        raise ValueError("--archive must select a regular file")
    toolchain = {name: observe(command) for name, command in {
        "rustc": ["rustc", "--version", "--verbose"], "cargo": ["cargo", "--version"],
        "node": ["node", "--version"], "npm": ["npm", "--version"],
    }.items()}
    if sys.platform == "darwin":
        toolchain["sdk"] = observe(["xcrun", "--show-sdk-path"])
        toolchain["xcode"] = observe(["xcodebuild", "-version"])
        signing = {"display": observe(["codesign", "--display", "--verbose=4", str(app)]),
                   "verification": observe(["codesign", "--verify", "--deep", "--strict", "--verbose=2", str(app)])}
        signing["status"] = "verified" if signing["verification"]["exitCode"] == 0 else "failed-or-unavailable"
        signing["meaning"] = "Local codesign verification only; does not establish notarization, distribution identity or human acceptance."
    else:
        signing = {"status": "unexecuted", "meaning": "macOS codesign requires a macOS host."}
    if source_before != source_inventory() or package_before != package_inventory(app):
        raise ValueError("Source or package changed during receipt capture; retry after work and build finish")
    if archive is not None and archive_before != file_entry(archive, archive.name):
        raise ValueError("Archive changed during receipt capture; retry after archiving finishes")
    checks, check_source = reported_checks(checks_file)
    identities = {}
    for name, relative in {
        "nativeReference": "shared/reservoir-scope/reference-manifest.json",
        "nativeResources": "native/ReservoirScope/resource-manifest.json",
        "referenceScenes": "shared/reservoir-scope/fixtures/reference-scenes.json",
        "cargoLock": "desktop/ReservoirScope/Cargo.lock",
        "npmLock": "desktop/ReservoirScope/package-lock.json",
        "rustToolchain": "desktop/ReservoirScope/rust-toolchain.toml",
        "stagedResourceIndex": "desktop/ReservoirScope/src-tauri/resources/resource-index.json",
    }.items():
        identities[name] = file_entry(ROOT / relative, relative)
    baseline = json.loads((ROOT / "shared/reservoir-scope/reference-manifest.json").read_bytes())["baseline"]
    return {"schema": "reservoir-scope.qualification-receipt.v1", "capturedAtUtc": datetime.now(timezone.utc).isoformat(),
            "purpose": "Local candidate identity and evidence inventory; not a release or parity approval",
            "sourcePackageRelation": "Sources and package were co-captured after the reported build. This receipt alone does not prove that the binary was built from these sources.",
            "nativeBaseline": baseline, "repository": observe(["git", "rev-parse", "HEAD"], ROOT),
            "implementation": {"roots": ["desktop/ReservoirScope", "shared/reservoir-scope", ".github/workflows/tauri.yml"],
                               "excludedDirectoryNames": sorted(EXCLUDED_PARTS), "excludedPrefixes": list(EXCLUDED_PREFIXES),
                               "generatedPermissionsExclusion": "Small retained permissions/autogenerated outputs are excluded because build.rs regenerates command permissions; build.rs and capability files are hashed as authoritative inputs.",
                               "inventorySha256": inventory_digest(source_before), "files": source_before},
            "identities": identities, "host": {"system": platform.system(), "release": platform.release(),
                                                    "version": platform.version(), "architecture": platform.machine(),
                                                    "python": platform.python_version(),
                                                    "processOverrides": {name: os.environ[name] for name in ("SDKROOT", "DEVELOPER_DIR", "MACOSX_DEPLOYMENT_TARGET") if name in os.environ}},
            "toolchain": toolchain, "package": package_before, "archive": archive_before, "codesign": signing,
            "checks": checks, "checkEvidenceFile": check_source,
            "qualificationGates": [
                {"id": "macos-packaged-human-acceptance", "status": "unexecuted", "scope": "Actual graphics, exact selection, context recovery, file dialogs, accessibility and lifecycle"},
                {"id": "windows-x64-package-and-ui", "status": "unexecuted", "scope": "Build/install/launch, WebView2, native dialogs, GPU and accessibility"},
                {"id": "linux-x64-package-and-ui", "status": "unexecuted", "scope": "Build/install/launch, WebKitGTK, display server/GPU, native dialogs and accessibility"},
                {"id": "public-distribution-signing", "status": "unexecuted", "scope": "Notarization, Windows signing and public release delivery"},
                {"id": "full-native-parity", "status": "incomplete", "scope": "Remaining roadmap milestones and cross-platform acceptance"}],
            "notes": notes}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--checks-file", type=Path)
    parser.add_argument("--archive", type=Path, help="Optional completed package archive to hash; this tool does not create it")
    parser.add_argument("--note", action="append", default=[])
    args = parser.parse_args()
    try:
        receipt = capture(args.app.resolve(), args.checks_file, args.note, args.archive)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        # Evidence is append-only: existing receipts are never replaced.
        with args.output.open("x", encoding="utf-8") as output:
            json.dump(receipt, output, indent=2, sort_keys=True)
            output.write("\n")
        print(json.dumps({"status": "captured", "output": str(args.output.resolve()),
                          "sourceFiles": len(receipt["implementation"]["files"]),
                          "packageFiles": len(receipt["package"]["files"]),
                          "codesign": receipt["codesign"]["status"]}))
    except (OSError, ValueError, KeyError, plistlib.InvalidFileException) as error:
        parser.exit(1, f"Receipt capture failed: {error}\n")


if __name__ == "__main__":
    main()
